#!/usr/bin/env python3
"""Builds app/src/main/resources/exifwipe/places.tsv for randomized GPS positions.

Inputs (download separately; they are not stored in this repository):
  - GeoNames cities15000.txt  https://download.geonames.org/export/dump/cities15000.zip
    (CC BY 4.0, https://www.geonames.org/)
  - Natural Earth 1:10m land and lakes shapefiles (public domain, https://www.naturalearthdata.com/)
    ne_10m_land.shp, ne_10m_minor_islands.shp, ne_10m_lakes.shp

For each populated place with at least MIN_POP inhabitants the script stores its position,
population, elevation (GeoNames 'dem' column, SRTM/GTOPO30 based), IANA time zone and a small
land mask: an 11 x 11 grid of 1 km cells centred on the place. A bit is set only if a 6 x 6 grid of
sample points covering the cell (edges included) lies on land and outside lakes according to Natural Earth 1:10m. The app picks a random set
cell within the place's radius and a random point inside it, so the point is always on land at
that map scale and never exactly the city centre.

Usage: python3 tools/build_places.py <dir with the inputs> app/src/main/resources/exifwipe/places.tsv
Needs: shapely, pyshp.
"""
import math
import sys

import numpy as np
import shapefile
import shapely
from shapely.geometry import shape

MIN_POP = 50000
GRID = 11  # cells per side, odd so the centre cell is the city centre
CELL_KM = 1.0
SAMPLES = 6  # points per cell side tested; a cell counts as land only if all are on land
SKIP_CODES = {"PPLX", "PPLQ", "PPLH", "PPLW", "PPLCH"}  # city sections, abandoned, historical, destroyed


def load(path):
    return [shape(s.__geo_interface__) for s in shapefile.Reader(path).shapes()]


def radius_km(pop):
    return max(1.5, min(5.0, math.sqrt(pop) / 400.0))


def main(src, out):
    land = shapely.union_all(load(f"{src}/ne_10m_land.shp") + load(f"{src}/ne_10m_minor_islands.shp"))
    lakes = shapely.union_all(load(f"{src}/ne_10m_lakes.shp"))
    shapely.prepare(land)
    shapely.prepare(lakes)

    rows = []
    for line in open(f"{src}/cities15000.txt", encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        pop = int(f[14] or 0)
        if pop < MIN_POP or f[7] in SKIP_CODES or f[6] != "P":
            continue
        rows.append((float(f[4]), float(f[5]), pop, int(f[16]) if f[16] not in ("", "-9999") else 0, f[17], f[8]))

    zones = sorted({r[4] for r in rows})
    zone_index = {z: i for i, z in enumerate(zones)}
    half = GRID // 2
    # Sample points inside one cell (fractions of a cell, edges included).
    fr = np.linspace(-0.5, 0.5, SAMPLES)
    sx, sy = np.meshgrid(fr, fr)
    sx, sy = sx.ravel(), sy.ravel()
    kept = 0
    with open(out, "w", encoding="utf-8") as o:
        o.write("# Populated places for randomized GPS. Generated by tools/build_places.py.\n")
        o.write("# Data: GeoNames cities15000 (CC BY 4.0, geonames.org) and Natural Earth 1:10m land/lakes (public domain).\n")
        o.write("# Z lines: time zone table. P lines: lat lon population elevation_m zone_index country radius_km land_mask_hex\n")
        for z in zones:
            o.write(f"Z\t{z}\n")
        for lat, lon, pop, dem, tz, cc in rows:
            dlat = CELL_KM / 110.574
            dlon = CELL_KM / (111.320 * math.cos(math.radians(lat)))
            r = radius_km(pop)
            cells = [(gx, gy) for gy in range(GRID) for gx in range(GRID)
                     if math.hypot(gx - half, gy - half) * CELL_KM <= r + 1e-9]
            xs = np.concatenate([lon + (gx - half + sx) * dlon for gx, gy in cells])
            ys = np.concatenate([lat + (gy - half + sy) * dlat for gx, gy in cells])
            ok = shapely.contains_xy(land, xs, ys) & ~shapely.contains_xy(lakes, xs, ys)
            ok = ok.reshape(len(cells), -1).all(axis=1)
            bits = 0
            for (gx, gy), good in zip(cells, ok):
                if good:
                    bits |= 1 << (gy * GRID + gx)
            if bits == 0:
                continue
            o.write(f"P\t{lat:.5f}\t{lon:.5f}\t{pop}\t{dem}\t{zone_index[tz]}\t{cc}\t{r:.1f}\t{bits:031x}\n")
            kept += 1
    print(f"places: {kept} of {len(rows)}; zones: {len(zones)}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
